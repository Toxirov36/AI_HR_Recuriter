// Generates apps/frontend/src/styles.dark.css from styles.css: for each rule using light surfaces,
// dark text or light borders, emit a `.dark <selector>` override with a mapped colour.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const postcss = require(path.join(root, 'node_modules/postcss'));
// The landing page and the sign-in page carry their own dark tokens, so only the app stylesheet is generated.
const FILES = ['styles'];

const COLOR = /(?<![\w-])white(?![\w-])|#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\(\s*[\d.]+[\s,]+[\d.]+[\s,]+[\d.]+(?:\s*[,/]\s*[\d.]+%?)?\s*\)/g;

function parse(c) {
  let r, g, b, a = 1;
  if (c === 'white') {
    r = g = b = 255;
  } else if (c[0] === '#') {
    let h = c.slice(1);
    if (h.length === 3) h = h.split('').map((x) => x + x).join('');
    r = parseInt(h.slice(0, 2), 16); g = parseInt(h.slice(2, 4), 16); b = parseInt(h.slice(4, 6), 16);
    if (h.length === 8) a = parseInt(h.slice(6, 8), 16) / 255;
  } else {
    const n = c.match(/[\d.]+%?/g);
    r = +n[0]; g = +n[1]; b = +n[2];
    if (n[3] !== undefined) a = n[3].endsWith('%') ? parseFloat(n[3]) / 100 : +n[3];
  }
  return { r, g, b, a };
}
const light = ({ r, g, b }) => (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
const withAlpha = (hex, a) => {
  if (a >= 0.999) return hex;
  const h = hex.slice(1);
  return `rgb(${parseInt(h.slice(0, 2), 16)} ${parseInt(h.slice(2, 4), 16)} ${parseInt(h.slice(4, 6), 16)} / ${+a.toFixed(3)})`;
};

function mapBg(c) {
  const p = parse(c);
  if (p.a < 0.4) return null;
  const L = light(p);
  if (L >= 0.97) return withAlpha('#131e1a', p.a);
  if (L >= 0.93) return withAlpha('#17261f', p.a);
  if (L >= 0.86) return withAlpha('#1c2d26', p.a);
  return null;
}
function mapText(c) {
  const p = parse(c);
  if (p.a < 0.4) return null;
  const L = light(p);
  const greenish = p.g >= p.r && p.g >= p.b && p.g - p.r > 25;
  if (L < 0.3) return withAlpha('#e6efea', p.a);
  if (greenish && L < 0.55) return withAlpha('#58c0a0', p.a);
  if (L < 0.62) return withAlpha('#93a8a0', p.a);
  return null;
}
function mapBorder(c) {
  const p = parse(c);
  if (p.a < 0.4) return null;
  return light(p) >= 0.8 ? withAlpha('#24352e', p.a) : null;
}

const kind = (prop) => {
  if (prop.startsWith('--')) {
    const words = prop.slice(2).split('-');
    if (words.includes('soft') || words.includes('bg') || words.includes('surface')) return mapBg;
    if (words.includes('border') || words.includes('line')) return mapBorder;
    if (['muted', 'text', 'ink', 'green'].some((w) => words.includes(w))) return mapText;
    return mapBg;
  }
  if (/^background(-color)?$/.test(prop)) return mapBg;
  if (prop === 'color') return mapText;
  if (/^(border(-(top|right|bottom|left))?(-color)?|outline(-color)?)$/.test(prop)) return mapBorder;
  return null;
};

function generate(name) {
const src = fs.readFileSync(path.join(root, `apps/frontend/src/${name}.css`), 'utf8');
const root_ = postcss.parse(src);
const out = [];
let rules = 0, decls = 0;
root_.walkRules((rule) => {
  if (rule.parent && rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  const emit = [];
  rule.walkDecls((d) => {
    const fn = kind(d.prop);
    if (!fn || /var\(|gradient|url\(/.test(d.value)) return;
    let changed = false;
    const value = d.value.replace(COLOR, (m) => {
      const mapped = fn(m);
      if (mapped) { changed = true; return mapped; }
      return m;
    });
    if (changed) emit.push(`  ${d.prop}: ${value}${d.important ? " !important" : ""};`);
  });
  if (!emit.length) return;
  const sels = rule.selectors.filter((s) => !/^\.dark\b|^:root/.test(s.trim()));
  if (!sels.length) return;
  const sel = sels.map((s) => `.dark ${s.trim().replace(/^(html|body)\b\s*/, '')}`.trim()).join(',\n');
  const block = `${sel} {\n${emit.join('\n')}\n}`;
  const chain = [];
  for (let p = rule.parent; p && p.type === 'atrule'; p = p.parent) {
    if (p.name === 'media' || p.name === 'supports') chain.unshift(`@${p.name} ${p.params}`);
  }
  out.push(chain.reduceRight((acc, head) => `${head} {\n${acc.split('\n').map((l) => '  ' + l).join('\n')}\n}`, block));
  rules++; decls += emit.length;
});

const header = '/* GENERATED by scripts/gen-dark-styles.cjs from styles.css; do not edit by hand. Re-run after changing light colours. */\n';
fs.writeFileSync(path.join(root, `apps/frontend/src/${name}.dark.css`), header + out.join('\n\n') + '\n');
console.log(`${name}: rules=${rules} declarations=${decls}`);
}
FILES.forEach(generate);
